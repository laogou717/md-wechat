// 合成最终样式表：基础样式 + 主题覆盖 + 用户自定义覆盖
export function buildStyles(theme, opts = {}) {
  const p = opts.accent || theme.primary
  const fs = opts.fontSize || 16
  const fontKey = opts.fontFamily && opts.fontFamily !== 'theme' ? opts.fontFamily : theme.font || 'sans'
  const font = FONT_STACKS[fontKey] || FONT_STACKS.sans
  const themed = Object.assign(baseStyles(p, fs, font), theme.styles(p, fs, font))

  // 强调色联动：主色整体替换 + 辅助色按表换算；用户自定义样式在其后合并，不受影响
  const replacements = []
  if (opts.accent && !ACCENT_REPLACE_OFF.has(theme.id)) {
    replacements.push([theme.primary, p])
    for (const [hex, mode] of Object.entries(ACCENT_TINTS[theme.id] || {})) {
      replacements.push([hex, mode === 'deep' ? deepenOf(p) : tintOf(p, Number(mode) || 0)])
    }
  }
  // 辅色槽位：独立于主色的配色按用户选择替换（浅底/深色变体随之派生）
  for (const slot of COLOR_SLOTS[theme.id] || []) {
    const chosen = opts.slotColors?.[slot.key]
    if (typeof chosen !== 'string' || !chosen) continue
    replacements.push([slot.base, chosen])
    for (const hex of slot.also || []) replacements.push([hex, chosen])
    for (const [hex, mode] of Object.entries(slot.tints || {})) {
      replacements.push([hex, mode === 'deep' ? deepenOf(chosen) : tintOf(chosen, Number(mode) || 0)])
    }
  }
  if (replacements.length) {
    for (const key of Object.keys(themed)) {
      let value = themed[key]
      if (typeof value !== 'string') continue
      for (const [from, to] of replacements) {
        value = value.replace(new RegExp(escapeReg(from), 'gi'), to)
      }
      themed[key] = value
    }
  }

  const styles = Object.assign(themed, opts.custom || {})

  if (opts.colorMode === 'dark') {
    for (const key of Object.keys(styles)) {
      if (typeof styles[key] !== 'string') continue
      styles[key] = styles[key].includes('style="')
        ? styles[key].replace(/style="([^"]*)"/g, (_, css) => `style="${darkStyle(css)}"`)
        : darkStyle(styles[key])
    }
  }

  // 跨主题的排版安全线：长 token 必须能在当前行断开；列表不应继承引用块
  // 或自定义容器的居中 / 首行缩进，否则 marker 会与正文分离。
  styles.container = `${styles.container}word-break:break-word;overflow-wrap:anywhere;`
  styles.ul = `${styles.ul}text-align:left;text-indent:0;list-style-position:outside;`
  styles.ol = `${styles.ol}text-align:left;text-indent:0;list-style-position:outside;`
  styles.li = `${styles.li}text-align:left;text-indent:0;`
  styles.liP = `${styles.liP}text-align:left;text-indent:0;`
  styles.bqP = `${styles.bqP}text-indent:0;`
  if (!styles.blockquoteNested) {
    // 嵌套引用降阶：剥掉外层引用的背景、虚线框与全边框，只留左边线，
    // 避免“泡中泡”事故。优先复用外层左边框颜色，其次主题主色。
    const borderColor =
      (styles.blockquote.match(/border-left:\s*\d+px\s+\w+\s+([^;]+);/) || [])[1]?.trim() || p
    styles.blockquoteNested = `margin:0.8em 0 0.4em;padding:0.15em 0 0.15em 0.9em;background-color:transparent;border:none;border-left:3px solid ${borderColor};border-radius:0;color:inherit;box-sizing:border-box;max-width:100%;`
  }

  return styles
}
